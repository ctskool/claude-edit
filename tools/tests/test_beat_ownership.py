class Emit(unittest.TestCase):
    def setUp(self):
        self.dir = tempfile.TemporaryDirectory()
        self.addCleanup(self.dir.cleanup)
        self.project = Path(self.dir.name)
        (self.project / "assets").mkdir()
        for name in ("face.mp4", "a.png", "logo.png", "unused.png"):
            (self.project / "assets" / name).write_bytes(name.encode())
        (self.project / "src.txt").write_text("source", encoding="utf8")
        (self.project / "plan.json").write_text(json.dumps(PLAN), encoding="utf8")
        self.lock = lock.derive(PLAN, 4, 30)

    def build(self, html=PAGE, chains=CHAINS, extra_roots=None, evidence=None, library=None, helpers=None):
        (self.project / "index.html").write_text(html, encoding="utf8", newline="\n")
        return ownership.emit(self.project, self.lock, chains, extra_roots or {}, {"cap.w0000-0001": "b1"}, evidence, library or (), helpers or ())

    def test_owners_and_frames(self):
        m = self.build()
        got = {o["id"]: o["frames"] for o in m["owners"]}
        self.assertEqual(got, {"scene.sc-a": [[0, 60]], "scene.sc-b": [[60, 120]], "cap.w0000-0001": [[0, 30]], "cap.w0002-0002": [[30, 120]],
                               "hud.one": [[15, 120]], "hud.two": [[75, 120]]})
        self.assertEqual(ownership.load(self.project)["composition_rev"], m["composition_rev"])

    def test_same_page_same_map(self):
        self.assertEqual(self.build(), self.build())

    def test_file_rules(self):
        m = self.build()
        files = m["shared"]["files"]
        self.assertNotIn("assets/a.png", files, "referenced only by an owner")
        self.assertIn("assets/logo.png", files, "referenced by an owner and the shell")
        self.assertIn("assets/face.mp4", files, "referenced by the shell")
        self.assertIn("assets/unused.png", files, "referenced by nobody")
        self.assertNotIn("index.html", files)
        self.assertNotIn("src.txt", files, "authoring")
        self.assertEqual(list(m["authoring"]), ["src.txt", "plan.json"])

    def test_owner_asset_bytes_touch_only_that_owner(self):
        old = self.build()
        (self.project / "assets" / "a.png").write_bytes(b"new bytes")
        r = ownership.invalidate(old, self.build(), self.lock)
        self.assertEqual((r["all"], r["beats"], r["owners_changed"]), (False, ["b1"], ["scene.sc-a"]))
        self.assertEqual(r["reasons"][0]["files"], ["assets/a.png"])

    def test_shared_asset_bytes_touch_everything(self):
        old = self.build()
        (self.project / "assets" / "logo.png").write_bytes(b"new bytes")
        r = ownership.invalidate(old, self.build(), self.lock)
        self.assertTrue(r["all"])
        self.assertIn("file:assets/logo.png", r["all_reasons"])

    def test_unreferenced_file_touches_everything(self):
        old = self.build()
        (self.project / "assets" / "unused.png").write_bytes(b"new bytes")
        self.assertTrue(ownership.invalidate(old, self.build(), self.lock)["all"])

    def test_a_new_undeclared_file_touches_everything(self):
        old = self.build()
        (self.project / "assets" / "new.png").write_bytes(b"x")
        self.assertIn("file:assets/new.png", ownership.invalidate(old, self.build(), self.lock)["all_reasons"])


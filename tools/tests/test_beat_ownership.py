class CarriedObjects(unittest.TestCase):
    CHAIN = {"id": "c", "objects": ["#a", "#b"], "carries": ["x", "opacity"], "links": ["hud.one", "hud.two", "hud.three"], "resets": []}
    STARTS = {"hud.one": 10, "hud.two": 50, "hud.three": 80}
    FULL = {"#a": {"x": 0, "opacity": 1}, "#b": {"x": 0, "opacity": 1}}
    SEEN = {"tweens": [["#a", 10, 40]], "measured": {"50": FULL}}

    def frames(self, reset, evidence=None):
        chain = {**self.CHAIN, "resets": [reset]}
        return ownership.link_frames(chain, self.STARTS, 100, evidence)

    def test_real_carried_object_with_no_reset_runs_to_the_end(self):
        old, new = maps()
        edit(new, "hud.seat1")
        r = run(old, new)
        want = [b for b in LOCK["beats"] if b["end_frame"] > 967]
        self.assertEqual(r["beats"], [b["beat_id"] for b in want])
        self.assertEqual(r["reasons"][0]["frames"], [[967, 3214]])
        self.assertFalse(r["all"])
        self.assertEqual(r["frames_touched"], 3214 - want[0]["start_frame"])

    def test_no_reset_means_every_link_reaches_the_end(self):
        frames, dropped = ownership.link_frames(self.CHAIN, self.STARTS, 100)
        self.assertEqual(frames, {"hud.one": [[10, 100]], "hud.two": [[50, 100]], "hud.three": [[80, 100]]})
        self.assertEqual(dropped, [])

    def test_complete_measured_reset_ends_earlier_links_only(self):
        frames, dropped = self.frames({"frame": 50, "values": self.FULL, "write": "set"}, self.SEEN)
        self.assertEqual(frames, {"hud.one": [[10, 50]], "hud.two": [[50, 100]], "hud.three": [[80, 100]]})
        self.assertEqual(dropped, [])

    def test_reset_that_declares_only_position_does_not_end_the_chain(self):
        partial = {"#a": {"x": 0}, "#b": {"x": 0}}
        seen = {"tweens": [], "measured": {"50": partial}}
        frames, dropped = self.frames({"frame": 50, "values": partial, "write": "set"}, seen)
        self.assertEqual(frames["hud.one"], [[10, 100]])
        self.assertIn("#a opacity", dropped[0]["why"])

    def test_reset_missing_one_object_does_not_end_the_chain(self):
        values = {"#a": self.FULL["#a"]}
        frames, dropped = self.frames({"frame": 50, "values": values, "write": "set"}, {"measured": {"50": values}})
        self.assertEqual(frames["hud.one"], [[10, 100]])
        self.assertIn("#b x", dropped[0]["why"])

    def test_a_to_is_never_a_reset(self):
        frames, dropped = self.frames({"frame": 50, "values": self.FULL, "write": "to"}, self.SEEN)
        self.assertEqual(frames["hud.one"], [[10, 100]])
        self.assertEqual(dropped[0]["why"], "not an absolute write")

    def test_undeclared_write_kind_is_not_a_reset(self):
        frames, _ = self.frames({"frame": 50, "values": self.FULL}, self.SEEN)
        self.assertEqual(frames["hud.one"], [[10, 100]])

    def test_a_crossing_tween_keeps_the_chain_open(self):
        seen = {"tweens": [["#b", 45, 60]], "measured": {"50": self.FULL}}
        frames, dropped = self.frames({"frame": 50, "values": self.FULL, "write": "fromTo"}, seen)
        self.assertEqual(frames["hud.one"], [[10, 100]])
        self.assertIn("crosses", dropped[0]["why"])

    def test_the_resets_own_tween_does_not_cross_it(self):
        seen = {"tweens": [["#a", 50, 60]], "measured": {"50": self.FULL}}
        frames, _ = self.frames({"frame": 50, "values": self.FULL, "write": "fromTo"}, seen)
        self.assertEqual(frames["hud.one"], [[10, 50]])

    def test_an_unmeasured_reset_keeps_the_chain_open(self):
        frames, dropped = self.frames({"frame": 50, "values": self.FULL, "write": "set"})
        self.assertEqual(frames["hud.one"], [[10, 100]])
        self.assertEqual(dropped[0]["why"], "not measured")

    def test_a_wrong_measurement_drops_the_reset(self):
        seen = {"measured": {"50": {"#a": {"x": 3, "opacity": 1}, "#b": {"x": 0, "opacity": 1}}}}
        frames, dropped = self.frames({"frame": 50, "values": self.FULL, "write": "set"}, seen)
        self.assertEqual(frames["hud.one"], [[10, 100]])
        self.assertIn("do not match", dropped[0]["why"])

    def test_a_reset_with_no_link_on_its_frame_has_no_owner(self):
        seen = {"measured": {"60": self.FULL}}
        frames, dropped = self.frames({"frame": 60, "values": self.FULL, "write": "set"}, seen)
        self.assertEqual(frames["hud.one"], [[10, 100]])
        self.assertIn("no link", dropped[0]["why"])



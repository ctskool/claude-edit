class Invalidate(unittest.TestCase):
    def test_nothing_changed(self):
        r = run(*maps())
        self.assertEqual((r["all"], r["beats"], r["frames_touched"], r["share"]), (False, [], 0, 0.0))

    def test_caption_labelled_b02_starts_inside_b01(self):
        old, new = maps()
        edit(new, "cap.w0006-0008")
        r = run(old, new)
        self.assertLess(BEATS["b01"]["start_frame"], 65)
        self.assertLess(65, BEATS["b02"]["start_frame"])
        self.assertEqual(r["beats"], ["b01", "b02"])
        self.assertEqual(r["frames_touched"], BEATS["b02"]["end_frame"])
        self.assertFalse(r["all"])
        self.assertEqual([x["beat"] for x in r["reasons"]], ["b01", "b02"])
        self.assertEqual(r["reasons"][0]["change"], "changed")

    def test_scene_group_spans_its_beats_and_skips_the_gap(self):
        old, new = maps()
        edit(new, "scene.sc-grid")
        r = run(old, new)
        self.assertEqual(r["beats"], ["b07", "b09", "b10", "b11", "b12"])
        self.assertNotIn("b08", r["beats"])

    def test_deleted_content_touches_where_it_was(self):
        old, new = maps()
        new["owners"] = [o for o in new["owners"] if o["id"] != "cap.w0006-0008"]
        r = run(old, new)
        self.assertEqual(r["beats"], ["b01", "b02"])
        self.assertEqual({x["change"] for x in r["reasons"]}, {"removed"})

    def test_added_content_touches_where_it_lands(self):
        old, new = maps()
        new["owners"].append({"id": "cap.w9000-9001", "kind": "caption", "frames": [[1500, 1510]], "hash": "x"})
        r = run(old, new)
        self.assertEqual(r["beats"], beats_at(1500, 1510))
        self.assertEqual({x["change"] for x in r["reasons"]}, {"added"})

    def test_moved_content_touches_old_and_new(self):
        old, new = maps()
        edit(new, "cap.w0006-0008", frames=[[1500, 1510]])
        r = run(old, new)
        self.assertEqual(r["beats"], ["b01", "b02"] + beats_at(1500, 1510))

    def test_moved_content_changes_keys_on_both_sides_and_nowhere_else(self):
        old, new = maps()
        edit(new, "cap.w0006-0008", frames=[[1500, 1510]])
        before, after = keys(old), keys(new)
        changed = [b for b in before if before[b] != after[b]]
        self.assertEqual(changed, run(old, new)["beats"])

    def test_keys_agree_with_invalidate_for_each_kind(self):
        for id_ in ("cap.w0006-0008", "scene.sc-grid", "hud.seat1", "scene.sc-vo"):
            old, new = maps()
            edit(new, id_)
            before, after = keys(old), keys(new)
            self.assertEqual([b for b in before if before[b] != after[b]], run(old, new)["beats"], id_)

    def test_undeclared_file_touches_everything(self):
        r = run(*maps(), ["assets/stills/nobody-declared-this.png"])
        self.assertTrue(r["all"])
        self.assertEqual(r["beats"], [b["beat_id"] for b in LOCK["beats"]])
        self.assertEqual(r["share"], 1.0)
        self.assertIn("unknown_file:assets/stills/nobody-declared-this.png", r["all_reasons"])

    def test_paths_outside_the_project_touch_everything(self):
        for path in ("../other/style.css", "C:/nonportable/x.css", "/etc/x", "renders/../../x.css"):
            r = run(*maps(), [path])

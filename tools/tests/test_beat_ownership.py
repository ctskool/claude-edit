class Positions(unittest.TestCase):
    """A position that is not a number lands relative to whatever tween came last, which is in another block, so editing that block moves this one with no key change."""

    setUp = Emit.setUp
    build = Emit.build
    refused = Emit.refused
    HELPERS = {"A": 1, "on": 2}

    def stops(self, line):
        with self.subTest(line=line):
            self.refused(page(a_js=A_JS + "        " + line + "\n"), "not a number|no position|relative position|other than by a call", helpers=self.HELPERS)

    def holds(self, line):
        with self.subTest(line=line):
            self.assertEqual(self.build(page(a_js=A_JS + "        " + line + "\n"), helpers=self.HELPERS)["shared"]["unconfined"], {})

    def test_a_string_behind_a_name_stops_the_build(self):
        self.stops('const P0 = ">"; tl.to("#a", { x: 1 }, P0);')
        self.stops('const P1 = ">"; on("#a", P1);')
        self.stops('const P2 = ">"; tl.to("#a", { x: 1 }, P2 + 1);')
        self.stops('let P3 = 1; P3 = ">"; tl.to("#a", { x: 1 }, P3);')

    def test_undefined_stops_the_build(self):
        self.stops('tl.to("#a", { x: 1 }, undefined);')
        self.stops('on("#a", undefined);')

    def test_a_helper_given_a_string_stops_the_build(self):
        self.stops('on("#a", ">");')

    def test_a_short_row_or_a_string_column_stops_the_build(self):
        self.stops('[[1]].forEach(([j0, j1]) => tl.to("#a", { x: j0 }, j1));')
        self.stops('[[1, ">"]].forEach(([j0, j1]) => tl.to("#a", { x: j0 }, j1));')
        self.stops('[">"].forEach((j0) => on("#a", j0));')

    def test_anything_but_arithmetic_stops_the_build(self):
        self.stops('tl.to("#a", { x: 1 }, (0, ">"));')
        self.stops('tl.to("#a", { x: 1 }, 1 ? ">" : 0);')
        self.stops('tl.to("#a", { x: 1 }, [1][0]);')
        self.stops('tl.to("#a", { x: 1 }, Math.floor(1.5));')

    def test_the_nearest_binding_is_the_one_read(self):
        self.stops('[1].forEach((j0) => { [">"].forEach((j0) => tl.to("#a", { x: 1 }, j0)); });')

    def test_a_timeline_or_helper_handed_on_stops_the_build(self):
        self.stops('const t2 = tl; t2.to("#a", { x: 1 }, ">");')
        self.stops('const t3 = tl;')
        self.stops('tl.to.apply(tl, ["#a", { x: 1 }, ">"]);')
        self.stops('tl["to"]("#a", { x: 1 }, ">");')
        self.stops('const h0 = on; h0("#a", ">");')
        self.stops('on.call(null, "#a", ">");')
        self.stops('[["#a", 1]].forEach(on);')

    def test_a_blocks_own_function_is_read_through_its_calls(self):
        self.stops('const f0 = (s, t) => tl.to(s, { x: 1 }, t); f0("#a", ">");')
        self.stops('const f1 = (s, t) => tl.to(s, { x: 1 }, t); f1("#a");')
        self.stops('const f2 = (s, t) => tl.to(s, { x: 1 }, t); f2("#a", 1); f2("#a", ">");')
        self.stops('const f3 = (s, t) => tl.to(s, { x: 1 }, t); [["#a", ">"]].forEach(([j0, j1]) => f3(j0, j1));')
        self.stops('function f4(s, t) { tl.to(s, { x: 1 }, t); } f4("#a", ">");')
        self.stops('const f5 = (s, t) => tl.to(s, { x: 1 }, t); const f6 = f5; f6("#a", ">");')

    def test_a_block_that_is_not_confined_gets_no_credit_for_its_names(self):
        self.stops('const k0 = [1]; k0.push(">"); k0.forEach((j0) => tl.to("#a", { x: 1 }, j0));')

    def test_what_real_blocks_do_builds(self):
        self.holds('tl.to("#a", { x: 1 }, 1 + 0.07 * 2);')
        self.holds('tl.to("#a", { x: 1 }, A(1.5));')
        self.holds('on("#a", A(1.5), 0.2);')
        self.holds('const P0 = 1; tl.to("#a", { x: 1 }, P0 + 0.5);')
        self.holds('[1, 1.5].forEach((j0, j1) => on("#a", j0 + 0.1 * j1, 0.1));')
        self.holds('[[1, 2], [1.5, 3]].forEach(([j0, j1]) => tl.to("#a", { x: j1 }, j0));')
        self.holds('const f0 = (s, t) => tl.to(s, { x: 1 }, t); f0("#a", 1); f0("#a", 1.5);')
        self.holds('function f1(s, t) { tl.to(s, { x: 1 }, t); } f1("#a", 1);')
        self.holds('const R0 = [1, 2]; R0.slice(1).forEach((j0, j1) => on("#a", 1 + j1));')
        self.holds('const R1 = [[1, 2]]; R1.forEach(([j0]) => on("#a", j0));')
        self.holds('const R2 = [1, 2], L0 = 0.4 / (R2.length - 1); R2.forEach((j0, j1) => on("#a", 1 + L0 * j1));')
        self.holds('for (let i = 0; i < 2; i++) { on("#a", 1 + i); }')
        self.holds('[[1, 1], [2, 2]].forEach(([j0, j1]) => { [0, 1].forEach((j2) => on("#a", j0 + j2 * j1)); });')

    def test_the_real_page_has_no_position_this_cannot_prove(self):
        blocks, _ = ownership.js_regions((FIXTURE / "index.html").read_text(encoding="utf8"))
        self.assertEqual({id_: found for id_, found in ((i, confine.block_problems(b, MAP_HELPERS, [])) for i, b in blocks.items()) if found}, {})



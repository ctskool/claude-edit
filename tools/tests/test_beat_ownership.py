def maps():
    return copy.deepcopy(MAP), copy.deepcopy(MAP)


def owner(m, id_):
    return next(o for o in m["owners"] if o["id"] == id_)


def edit(m, id_, frames=None):
    """The owner's generated bytes changed, and maybe its frames with them."""
    o = owner(m, id_)
    o["hash"] = sha(o["hash"] + "edited")
    if frames:
        o["frames"] = frames


def run(old, new, changed_files=None):
    return ownership.invalidate(old, new, LOCK, changed_files)


def beats_at(start, end=None):
    """Beats from the one holding frame start, through the one holding end - 1."""
    end = end or start + 1
    return [b["beat_id"] for b in LOCK["beats"] if b["start_frame"] < end and start < b["end_frame"]]


def keys(m):
    return {b["beat_id"]: ownership.input_key(b, LOCK, m, PROFILE, ENGINE) for b in LOCK["beats"]}



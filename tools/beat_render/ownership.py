"""What a change touches, for a beat-rendered project. CONTRACT.md sections 3, 4 and 5.

emit() runs inside the project's build, after index.html is written. It hashes generated output plus asset bytes, never source text,
because a picture is a function of index.html, its assets and the engine. Regions and rows are declared; nothing is inferred from Python or GSAP.
Every generated byte outside a declared region is the shell, and the shell touches everything. A region that can reach past its own scene stays in the shell too (confine.py).
No ownership.json also means everything.
"""
import json, os, posixpath, re, sys
from pathlib import Path
from urllib.parse import unquote

sys.path.append(str(Path(__file__).resolve().parent.parent))
import confine
import sound_mix
from common import frame_of, overlaps, sha

SCHEMA = 1
NAME = "ownership.json"
TEMPLATE = "ivory"
IGNORED = ["renders/", "snaps", "verification/", ".hyperframes/", "tools_local/_bak/", "tools_local/__pycache__/",
           "assets/sfx/", "assets/voice.m4a", "sound.json", "STORYBOARD.md", "CLAUDE.md",
           "ownership.json", "beats.lock.json", "events.json",
           "tools_local/chunks/", "plan.parts/", "plan.lead.json"]  # parallel-build inputs: merge_chunks.py writes the sources that count
DOM_MARK = re.compile(r"<!--@own ([\w.-]+)-->|<!--@/own-->")
JS_MARK = re.compile(r'^[ \t]*own\((?:"([\w.-]+)"|null)\);[ \t]*$', re.M)
ASSET = re.compile(r'src="(assets/[^"]+)"')
VIDEO = re.compile(r"<video\b[^>]*>", re.I)
AUDIO = re.compile(r"<audio\b[^>]*>", re.I)  # sound is not picture: an audio tag naming an ignored file does not put it in the picture
DYNAMIC_ASSET = re.compile(r"assets/(?![\w./-]+\.\w+)")  # assets/ not followed by a whole file name: the page may build a path at runtime


def merge(frames):
    """Half-open intervals, sorted and joined."""
    out = []
    for a, b in sorted(frames):
        if a >= b:
            continue
        if out and a <= out[-1][1]:
            out[-1][1] = max(out[-1][1], b)
        else:
            out.append([a, b])
    return out


def is_ignored(path):
    return any(path.startswith(prefix) for prefix in IGNORED)


# ---- regions of generated output


def dom_regions(html):
    regions, spans, opened = {}, [], None
    for m in DOM_MARK.finditer(html):
        if m[1]:
            if opened:
                raise ValueError(f"nested @own: {m[1]} inside {opened[0]}")
            opened = (m[1], m.start(), m.end())
        else:
            if not opened:
                raise ValueError("@/own with no open @own")
            id_, start, inner = opened
            if id_ in regions:
                raise ValueError(f"duplicate DOM region: {id_}")
            regions[id_] = html[inner:m.start()]
            spans.append((start, m.end(), id_))
            opened = None
    if opened:
        raise ValueError(f"unmatched @own: {opened[0]}")
    return regions, spans


def js_regions(html):
    """A block runs from its own("id"); line to the next own(...) line."""
    marks = list(JS_MARK.finditer(html))
    if len(re.findall(r"\bown\(", html)) != len(marks) + 1:  # the + 1 is the function itself
        raise ValueError("an own() call the marker pattern cannot read")
    if marks and marks[-1][1]:
        raise ValueError(f"JS block left open: {marks[-1][1]}")
    regions, spans = {}, []
    for m, after in zip(marks, marks[1:]):
        if m[1]:
            if m[1] in regions:
                raise ValueError(f"duplicate JS block: {m[1]}")
            regions[m[1]] = html[m.start():after.start()]
            spans.append((m.start(), after.start(), m[1]))
    return regions, spans


def data_of(html, name):
    """The JSON after a /*@NAME*/ marker, and its span."""
    marker = f"/*@{name}*/"
    if html.count(marker) != 1:
        raise ValueError(f"{marker} must appear once, found {html.count(marker)}")
    start = html.index(marker) + len(marker)
    value, end = json.JSONDecoder().raw_decode(html, start)
    return value, (start, end, name)


def blank(html, spans):
    """html with each span replaced by its name. This is the shell."""
    out, at = [], 0
    for start, end, name in sorted(spans):
        if start < at:
            raise ValueError(f"overlapping regions at {name}")
        out += [html[at:start], f"<<{name}>>"]
        at = end
    return "".join(out + [html[at:]])


def script_of(shell):
    return shell[shell.rindex("<script>"):] if "<script>" in shell else shell


def check_block_names(blocks, shell):
    """A block's hash covers its own text. A constant read from outside it could change a picture no hash saw, so refuse it."""
    script = confine.code_only(script_of(shell))
    code = {id_: confine.code_only(block) for id_, block in blocks.items()}
    for id_, block in blocks.items():
        others = [script] + [text for other, text in code.items() if other != id_]
        for name in confine.top_names(block):
            used = re.compile(rf"(?<![\w$.\"'#-]){re.escape(name)}(?![\w$])")
            if any(used.search(text) for text in others):
                raise ValueError(f"{id_} declares {name}, and code outside the block uses it")


# ---- chains


def reset_problem(chain, reset, starts, evidence):
    """None if this reset ends the chain, else why not. CONTRACT.md section 3's four rules, plus that a link opens on it, so what it writes has an owner."""
    values = reset.get("values", {})
    missing = [f"{o} {p}" for o in chain["objects"] for p in chain["carries"] if p not in values.get(o, {})]
    if missing:
        return "does not cover " + ", ".join(missing)
    if reset.get("write") not in ("set", "fromTo"):
        return "not an absolute write"
    frame = reset["frame"]
    if frame not in starts:
        return f"no link starts at frame {frame}"
    if evidence is None:
        return "not measured"
    for target, start, end in evidence.get("tweens", []):
        if target in chain["objects"] and start < frame < end:
            return f"tween on {target} crosses frame {frame}"
    if evidence.get("measured", {}).get(str(frame)) != values:
        return f"measured values at frame {frame} do not match"
    return None


def link_frames(chain, starts, total, evidence=None):
    """Each link runs to the end unless a valid reset stops it. Returns its frames, and the resets dropped and why."""
    stops, dropped = [], []
    for reset in chain.get("resets", []):
        why = reset_problem(chain, reset, list(starts.values()), evidence)
        if why:
            dropped.append({"frame": reset.get("frame"), "why": why})
        else:
            stops.append(reset["frame"])
    return {link: [[start, min([f for f in stops if f > start], default=total)]] for link, start in starts.items()}, dropped


# ---- emit


def project_files(project):
    for path in sorted(project.rglob("*")):
        if path.is_file():
            yield path.relative_to(project).as_posix()


def scene_owners(doms, blocks, windows, extra_roots, total, fps, hash_of):
    frames = {}
    for sel, a, b in windows:
        frames.setdefault("scene." + sel.lstrip("#"), []).append([frame_of(a, fps), min(frame_of(b, fps), total)])
    if set(doms) != set(blocks):
        raise ValueError(f"DOM regions and JS blocks differ: {sorted(set(doms) ^ set(blocks))}")
    if set(frames) != set(doms):
        raise ValueError(f"windows and owners differ: {sorted(set(frames) ^ set(doms))}")
    owners = []
    for id_ in sorted(doms):
        spans = merge(frames[id_])
        extra = extra_roots.get(id_, [])
        if extra:
            # A write into shared DOM is seen past the scene's own window, and nothing here proves when it stops, so it reaches the end.
            spans = merge(spans + [[spans[0][0], total]])
        assets = {rel: hash_of(rel) for rel in sorted(set(ASSET.findall(doms[id_])))}
        body = {"kind": "scene", "frames": spans, "dom": doms[id_], "js": blocks[id_], "assets": assets}
        owners.append({"id": id_, "kind": "scene", "frames": spans, "roots": ["#" + id_.split(".", 1)[1], *extra], "hash": sha(body), "assets": assets})
    return owners


def caption_owners(rows, cap_beats, total, fps):
    owners, seen = [], set()
    for row in rows:
        on, off, _, _, id_ = row
        if id_ in seen:
            raise ValueError(f"duplicate caption owner: {id_}")
        seen.add(id_)
        frames = merge([[frame_of(on, fps), min(frame_of(off, fps), total)]])
        owners.append({"id": id_, "kind": "caption", "frames": frames, "beat": cap_beats.get(id_), "hash": sha({"kind": "caption", "frames": frames, "row": row})})
    return owners


def chain_owners(rows, declared, total, fps, evidence):
    by_id = {"hud." + name: t for name, t in rows}
    owners, chains, linked = [], [], set()
    for chain in declared:
        unknown = [x for x in chain["links"] if x not in by_id]
        if unknown:
            raise ValueError(f"chain {chain['id']} names links with no row: {unknown}")
        linked.update(chain["links"])
        starts = {x: frame_of(by_id[x], fps) for x in chain["links"]}
        frames, dropped = link_frames(chain, starts, total, evidence)
        # The chain's declaration is part of every link, so a changed reset changes what each link reaches.
        decl = sha(chain)
        chains.append({**chain, "dropped": dropped})
        for link in chain["links"]:
            row = [link, by_id[link]]
            owners.append({"id": link, "kind": "hud", "chain": chain["id"], "frames": frames[link], "hash": sha({"kind": "hud", "frames": frames[link], "row": row, "chain": decl})})
    loose = sorted(set(by_id) - linked)
    if loose:
        raise ValueError(f"rows in no chain: {loose}")
    return owners, chains


def emit(project, lock, chains, extra_roots, cap_beats, evidence=None, library=(), helpers=()):
    """Writes ownership.json from the index.html on disk. Any bad marker raises and leaves no map, and no map means everything.

    library: declared folders of stills. A file there that the page never names is out of the picture, so it stays out of the shared files,
    and pointing a card at another still does not touch everything. A page that may build a path at runtime gets no such exemption.
    helpers: shell helpers a confined block may call, name to the arguments it needs before it has a time. A block calling anything else is not confined.
    """
    project = Path(project)
    (project / NAME).unlink(missing_ok=True)
    html = (project / "index.html").read_text(encoding="utf8")
    fps, total = lock["fps"], lock["total_frames"]
    cache = {}

    def hash_of(rel):
        if rel not in cache:
            path = project / rel
            cache[rel] = sound_mix.file_hash(path) if path.is_file() else "MISSING"
        return cache[rel]

    doms, dom_spans = dom_regions(html)
    blocks, js_spans = js_regions(html)
    caps, caps_span = data_of(html, "CAPS")
    hud, hud_span = data_of(html, "HUD")
    windows, _ = data_of(html, "WINDOWS")
    runs, _ = data_of(html, "RUNS")
    duration, _ = data_of(html, "END")
    closed = blank(html, dom_spans + js_spans + [caps_span, hud_span])
    check_block_names(blocks, closed)
    placed = confine.position_problems(confine.code_only(script_of(closed)))
    if placed:
        raise ValueError(f"shell: {'; '.join(dict.fromkeys(placed))}")
    # What can reach past its own scene stays in the shell text, so its bytes are in every key and any change to it touches everything.
    unconfined = confine.reach(doms, blocks, closed, helpers)
    loose_caps = confine.caption_reach(caps)
    unconfined.update({id_: ["markup beyond <b>"] for id_ in loose_caps})
    shell = blank(html, [s for s in dom_spans + js_spans if s[2] not in unconfined] + ([] if loose_caps else [caps_span]) + [hud_span])

    owners = scene_owners(doms, blocks, windows, extra_roots, total, fps, hash_of)
    owners += caption_owners(caps, cap_beats, total, fps)
    linked, chains_out = chain_owners(hud, chains, total, fps, evidence)
    owners += linked

    plan = json.loads((project / "plan.json").read_text(encoding="utf8"))
    authoring = {rel: hash_of(rel) for rel in [*plan.get("composition_files", []), "plan.json"]}
    owner_assets = {rel for o in owners if o["id"] not in unconfined for rel in o.get("assets", {})}
    timing ={"duration": duration, "runs": runs, "windows": [[sel.lstrip("#"), a, b] for sel, a, b in windows]}
    media = []
    for tag in VIDEO.findall(html):
        a = sound_mix.attrs(tag)
        src = a.get("src", "")
        media.append({"id": a.get("id"), "src": src, "sha256": hash_of(src), "data-start": a.get("data-start"), "data-duration": a.get("data-duration"), "data-media-start": a.get("data-media-start")})
    files, unused = {}, []
    page = unquote(html)
    picture = unquote(AUDIO.sub("", html))
    dynamic = bool(DYNAMIC_ASSET.search(page))
    exempt = tuple(library) if not dynamic else ()

    def owned_only(rel):
        """Local only if every mention of the file in the whole page is a src attribute in an owner's region. A url(), a JS string or the shell is another reader."""
        return rel in owner_assets and not dynamic and page.count(rel) == sum(unquote(dom).count(f'src="{rel}"') for dom in doms.values())

    for rel in project_files(project):
        if rel == "index.html" or rel in authoring:
            continue
        if is_ignored(rel):
            if rel in picture:  # the ignore list is for files the picture does not read
                files[rel] = hash_of(rel)
            continue
        if owned_only(rel):
            continue
        if exempt and rel.startswith(exempt) and rel not in page:
            unused.append(rel)
            continue
        files[rel] = hash_of(rel)

    m = {"schema": SCHEMA, "template": TEMPLATE, "html_sha256": hash_of("index.html"), "lock_revision": lock["revision"], "fps": fps, "total_frames": total,
         "shared": {"shell_hash": sha(shell), "timing_hash": sha({**timing, "lock_revision": lock["revision"]}), "media_hash": sha(media),
                    "files_hash": sha({"files": files, "library": list(library)}), "files": files, "library": list(library), "unused": unused,
                    "unconfined": unconfined, "timing": timing, "media": media},
         "ignored": IGNORED, "owners": owners, "chains": chains_out}
    m["composition_rev"] = sha(m)
    m["authoring"] = authoring
    path = project / NAME
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(json.dumps(m, indent=1, ensure_ascii=False) + "\n", encoding="utf8", newline="\n")
    os.replace(tmp, path)
    return m


def load(project):
    """The map, or None if it is missing, damaged, or not the map of this index.html. None means everything."""
    project = Path(project)
    try:
        m = json.loads((project / NAME).read_text(encoding="utf8"))
        html_sha256 = sound_mix.file_hash(project / "index.html")
    except (OSError, ValueError):
        return None
    body = {k: v for k, v in m.items() if k not in ("composition_rev", "authoring")}
    if m.get("schema") != SCHEMA or m.get("html_sha256") != html_sha256 or m.get("composition_rev") != sha(body):
        return None
    return m


# ---- invalidate


def asset_hashes(m):
    return {rel: h for o in (m or {}).get("owners", []) for rel, h in o.get("assets", {}).items()}


def clean_path(path):
    """A project-relative path with forward slashes, or None if it points outside the project."""
    p = str(path).replace("\\", "/")
    if p.startswith("/") or re.match(r"[A-Za-z]:", p):
        return None
    p = posixpath.normpath(p)
    return None if p == ".." or p.startswith("../") else p


def diff_keys(a, b):
    return sorted(k for k in set(a) | set(b) if a.get(k) != b.get(k))


def shared_reasons(old, new):
    """Step 2 and 3: what in the shared part differs, by name."""
    reasons, media_plan = [], False
    s0, s1 = old["shared"], new["shared"]
    if s0["timing_hash"] != s1["timing_hash"]:
        media_plan = True
        names = [k for k in ("duration", "runs", "windows") if s0["timing"].get(k) != s1["timing"].get(k)]
        reasons += ["timing:" + n for n in names] or ["timing:lock"]
    if s0["media_hash"] != s1["media_hash"]:
        media_plan = True
        rows0, rows1 = {r["id"]: r for r in s0["media"]}, {r["id"]: r for r in s1["media"]}
        reasons += ["media:" + str(k) for k in diff_keys(rows0, rows1)] or ["media"]
    if s0["shell_hash"] != s1["shell_hash"]:
        reasons.append("shell")
        reasons += ["unconfined:" + id_ for id_ in diff_keys(s0.get("unconfined", {}), s1.get("unconfined", {}))]
    if s0["files_hash"] != s1["files_hash"]:
        reasons += ["file:" + rel for rel in diff_keys(s0["files"], s1["files"])] or ["files"]
    return reasons, media_plan


def invalidate(old, new, lock, changed_files=None):
    """old, new: ownership maps, old may be None. changed_files: project-relative paths, or None for the diff of the maps.

    Runs every step and collects every reason. Nothing narrows a result. A wrong guess here costs time, never a wrong picture.
    """
    everything, media_plan = [], False
    # step 1
    if old is None or new is None:
        everything.append("no_ownership_map")
        media_plan = True
    else:
        everything += [f"{k}_changed" for k in ("schema", "fps", "total_frames", "lock_revision") if old.get(k) != new.get(k)]
        if new.get("schema") != SCHEMA:
            everything.append("unknown_schema")
        if new.get("lock_revision") != lock["revision"]:
            everything.append("map_is_not_of_this_lock")
        # steps 2 and 3. A map of some other shape has no shared part to compare, and everything is the answer to that too
        if "shared" in old and "shared" in new:
            reasons, media_plan = shared_reasons(old, new)
            everything += reasons
        else:
            everything.append("no_shared_part")
            media_plan = True
    # step 4
    authored0, authored1 = (old or {}).get("authoring", {}), (new or {}).get("authoring", {})
    assets0, assets1 = asset_hashes(old), asset_hashes(new)
    given = changed_files is not None
    paths = changed_files if given else diff_keys(authored0, authored1) + diff_keys(assets0, assets1)
    noted = set()
    for path in paths:
        rel = clean_path(path)
        if rel is None:
            everything.append(f"unknown_file:{path}")
        elif is_ignored(rel):
            continue
        elif rel in authored0 or rel in authored1 or rel in assets0 or rel in assets1:
            noted.add(rel)
            hashes = (authored0.get(rel), authored1.get(rel), assets0.get(rel), assets1.get(rel))
            if given and hashes[0] == hashes[1] and hashes[2] == hashes[3]:
                everything.append(f"stale_map:{rel}")  # named as changed, but both maps hold the same bytes
        else:
            everything.append(f"unknown_file:{rel}")
    # step 5
    owners0 = {o["id"]: o for o in (old or {}).get("owners", [])}
    owners1 = {o["id"]: o for o in (new or {}).get("owners", [])}
    rows, changed = [], []
    for id_ in sorted(set(owners0) | set(owners1)):
        a, b = owners0.get(id_), owners1.get(id_)
        if a and b and a["hash"] == b["hash"]:
            continue
        changed.append(id_)
        kind = "added" if a is None else "removed" if b is None else "changed"
        frames = merge((a["frames"] if a else []) + (b["frames"] if b else []))
        for beat in lock["beats"]:
            if overlaps(frames, beat):
                rows.append({"beat": beat["beat_id"], "owner": id_, "change": kind, "frames": frames, "files": sorted(noted)})
    if old and new and old.get("html_sha256") != new.get("html_sha256") and not changed and not everything:
        everything.append("html_changed_outside_every_region")
    touched = {r["beat"] for r in rows}
    beats = [b for b in lock["beats"] if everything or b["beat_id"] in touched]
    frames_touched = sum(b["end_frame"] - b["start_frame"] for b in beats)
    return {"all": bool(everything), "new_media_plan": media_plan, "beats": [b["beat_id"] for b in beats], "frames_touched": frames_touched,
            "share": 1.0 if everything else round(frames_touched / lock["total_frames"], 3), "owners_changed": changed,
            "all_reasons": list(dict.fromkeys(everything)), "reasons": rows}


# ---- segment key


def input_key(beat, lock, m, profile_hash, engine_hash):
    """A moved or deleted owner changes deps on both its old and new beats, so the key covers old and new with no history."""
    deps = sorted([o["id"], o["hash"]] for o in m["owners"] if overlaps(o["frames"], beat))
    return sha({"v": 1,
                "beat": [beat["beat_id"], beat["start_frame"], beat["end_frame"]],
                "grid": [lock["fps"], lock["total_frames"]],
                "profile": profile_hash, "engine": engine_hash,
                "timing": m["shared"]["timing_hash"], "media": m["shared"]["media_hash"],
                "shell": m["shared"]["shell_hash"], "files": m["shared"]["files_hash"],
                "deps": deps})
